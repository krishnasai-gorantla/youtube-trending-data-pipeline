#!/usr/bin/env python3
"""Refresh the static dashboard data from the latest successful AWS pipeline run.

This script is intended for GitHub Actions using AWS OIDC. It never modifies
AWS source data; it only reads the latest curated run and writes dashboard JSON.
"""
from __future__ import annotations

import json
import os
import time
from datetime import datetime, timezone
from pathlib import Path

import boto3

REGION = os.getenv("AWS_REGION", "us-east-1")
STATE_MACHINE_ARN = os.getenv(
    "STATE_MACHINE_ARN",
    "arn:aws:states:us-east-1:303102153405:stateMachine:youtube-trending-end-to-end",
)
DATABASE = "db_youtube_cleaned"
SAFE_TABLE = "youtube_pipeline_safe"
QUARANTINE_TABLE = "youtube_pipeline_quarantine"
WORKGROUP = "primary"
ATHENA_OUTPUT = os.getenv(
    "ATHENA_OUTPUT",
    "s3://aws-glue-assets-303102153405-us-east-1/temporary/automated-pipeline-dashboard/",
)
OUTPUT_FILE = Path("docs/dashboard/data.json")


def latest_successful_run() -> tuple[str, str, str]:
    sf = boto3.client("stepfunctions", region_name=REGION)
    response = sf.list_executions(
        stateMachineArn=STATE_MACHINE_ARN,
        statusFilter="SUCCEEDED",
        maxResults=20,
    )
    executions = response.get("executions", [])
    if not executions:
        raise RuntimeError("No successful pipeline execution is available.")
    execution_arn = executions[0]["executionArn"]
    description = sf.describe_execution(executionArn=execution_arn)
    output = json.loads(description["output"])
    run_id = output.get("run_id")
    if not run_id:
        raise RuntimeError(
            f"Successful execution {execution_arn} did not return a run_id."
        )
    completed_at = description['stopDate'].astimezone(timezone.utc).isoformat()
    return run_id, execution_arn, completed_at


def query_rows(sql: str) -> list[dict[str, str]]:
    athena = boto3.client("athena", region_name=REGION)
    started = athena.start_query_execution(
        QueryString=sql,
        QueryExecutionContext={"Database": DATABASE},
        WorkGroup=WORKGROUP,
        ResultConfiguration={"OutputLocation": ATHENA_OUTPUT},
    )
    query_id = started["QueryExecutionId"]
    deadline = time.monotonic() + 300
    while time.monotonic() < deadline:
        status = athena.get_query_execution(QueryExecutionId=query_id)[
            "QueryExecution"
        ]["Status"]
        state = status["State"]
        if state == "SUCCEEDED":
            break
        if state in ("FAILED", "CANCELLED"):
            raise RuntimeError(
                f"Athena query {query_id} {state}: "
                f"{status.get('StateChangeReason', 'no reason returned')}"
            )
        time.sleep(2)
    else:
        raise TimeoutError(f"Athena query {query_id} exceeded 300 seconds.")

    response = athena.get_query_results(
        QueryExecutionId=query_id, MaxResults=100
    )["ResultSet"]["Rows"]
    if not response:
        return []
    headers = [cell.get("VarCharValue", "") for cell in response[0]["Data"]]
    result = []
    for row in response[1:]:
        values = [cell.get("VarCharValue", "") for cell in row.get("Data", [])]
        values += [""] * (len(headers) - len(values))
        result.append(dict(zip(headers, values)))
    return result


def as_int(value: str) -> int:
    return int(float(value or 0))


def as_float(value: str) -> float:
    return float(value or 0)


def main() -> None:
    run_id, execution_arn, completed_at = latest_successful_run()
    # run_id is generated by Step Functions as a UUID; it is safe to interpolate.
    quality_rows = query_rows(
        f"""
        SELECT COUNT(*) AS safe_rows,
               COUNT(DISTINCT region) AS region_count,
               COUNT_IF(video_id IS NULL OR TRIM(video_id) = ''
                        OR UPPER(TRIM(video_id)) = '#NAME?') AS invalid_ids,
               COUNT(DISTINCT video_id) AS unique_videos
        FROM {SAFE_TABLE}
        WHERE run_id = '{run_id}'
        """
    )
    duplicate_rows = query_rows(
        f"""
        SELECT COUNT(*) AS duplicate_key_groups
        FROM (
            SELECT region, video_id, trending_date
            FROM {SAFE_TABLE}
            WHERE run_id = '{run_id}'
            GROUP BY region, video_id, trending_date
            HAVING COUNT(*) > 1
        )
        """
    )
    quarantine_rows = query_rows(
        f"""
        SELECT issue_type, COUNT(*) AS row_count
        FROM {QUARANTINE_TABLE}
        WHERE run_id = '{run_id}'
        GROUP BY issue_type
        """
    )
    regional_rows = query_rows(
        f"""
        SELECT region,
               COUNT(*) AS observations,
               COUNT(DISTINCT video_id) AS unique_videos,
               SUM(views) AS views,
               ROUND(AVG(views), 0) AS avg,
               ROUND(100.0 * (SUM(likes) + SUM(comment_count))
                     / NULLIF(SUM(views), 0), 4) AS engagement
        FROM {SAFE_TABLE}
        WHERE run_id = '{run_id}'
        GROUP BY region
        ORDER BY region
        """
    )
    video_rows = query_rows(
        f"""
        SELECT region, video_id,
               max_by(title, views) AS title,
               max_by(channel_title, views) AS channel,
               MAX(views) AS views,
               MAX(likes) AS likes
        FROM {SAFE_TABLE}
        WHERE run_id = '{run_id}'
        GROUP BY region, video_id
        ORDER BY views DESC
        LIMIT 10
        """
    )
    if not quality_rows or not regional_rows:
        raise RuntimeError(f"No dashboard rows returned for run_id={run_id}.")

    quality = quality_rows[0]
    quarantine = {
        row["issue_type"]: as_int(row["row_count"])
        for row in quarantine_rows
    }
    payload = {
        "generated_at_utc": completed_at,
        "run_id": run_id,
        "execution_arn": execution_arn,
        "quality": {
            "safe_rows": as_int(quality["safe_rows"]),
            "region_count": as_int(quality["region_count"]),
            "invalid_ids": as_int(quality["invalid_ids"]),
            "unique_videos": as_int(quality["unique_videos"]),
            "duplicate_key_groups": as_int(
                duplicate_rows[0]["duplicate_key_groups"]
            ) if duplicate_rows else 0,
            "quarantined_invalid_ids": quarantine.get("invalid_video_id", 0),
            "quarantined_conflicting_rows": quarantine.get(
                "conflicting_business_key", 0
            ),
        },
        "regions": [
            {
                "region": row["region"],
                "observations": as_int(row["observations"]),
                "unique": as_int(row["unique_videos"]),
                "views": as_int(row["views"]),
                "avg": as_int(row["avg"]),
                "engagement": as_float(row["engagement"]),
            }
            for row in regional_rows
        ],
        "videos": [
            {
                "region": row["region"],
                "id": row["video_id"],
                "title": row["title"],
                "channel": row["channel"],
                "views": as_int(row["views"]),
                "likes": as_int(row["likes"]),
            }
            for row in video_rows
        ],
    }
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(
        "DASHBOARD_REFRESH="
        + json.dumps(
            {
                "run_id": run_id,
                "safe_rows": payload["quality"]["safe_rows"],
                "regions": payload["quality"]["region_count"],
                "videos": len(payload["videos"]),
                "output": str(OUTPUT_FILE),
            },
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
